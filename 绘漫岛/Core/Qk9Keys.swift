    // MARK: - 解码

    private static func decode(_ bytes: [UInt8]) -> String {
        var out = [UInt8]()
        out.reserveCapacity(bytes.count)
        for (i, b) in bytes.enumerated() {
            out.append(b ^ xorKey[i % xorKey.count])
        }
        guard let s = String(bytes: out, encoding: .utf8) else {
            // 常量损坏 → 立即暴露，绝不在运行期静默用错误密钥
            fatalError("Qk9Keys: 常量解码失败（构建期错误）")
        }
        return s
    }

    // MARK: - 对外（与原明文常量同类型、同语义）

    static let aesIV: String = decode(ivBytes)
    static let keyPad: String = decode(padBytes)

    /// "S001=key1;S002=key2;..." → ["S001": "key1", "S002": "key2", ...]
    static let versionKeys: [String: String] = {
        var dict: [String: String] = [:]
        for pair in decode(vkBytes).split(separator: ";") {
            let kv = pair.split(separator: "=", maxSplits: 1)
            guard kv.count == 2 else { continue }
            dict[String(kv[0])] = String(kv[1])
        }
        return dict
    }()
