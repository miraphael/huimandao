/// ──────────────────────────────────────────────────────────────────────────────
/// 混淆常量（加固第 2 重）—— 敏感字符串不再以明文出现在二进制里
///
/// 为什么需要：图源解密密钥（`versionKeys` / `aesIV` / `keyPad`）原本是
