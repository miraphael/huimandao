///
/// ⚠️ 这不防**动态**逆向（运行时内存里仍是明文），但能挡住
///    绝大多数「strings 一下 / 解包看常量」的低成本抄取 —— 性价比很高。
///
/// 🔴 约束：**不得影响功能**。
///    `enum` 的 `static let` 是懒加载且线程安全的，解码只在首次访问时执行一次，
///    之后与原来的明文常量**完全等价**（同样是 `String` / `[String: String]`）。
///    若解码失败会走 `fatalError` —— 那是**构建期就该发现的常量错误**，
///    不应该在运行期静默返回错误密钥（那会导致加密规则解密出乱码，极难排查）。
